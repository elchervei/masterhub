create table if not exists public.portfolio_items (
  id uuid primary key default gen_random_uuid(),
  master_id uuid not null references public.masters(id) on delete cascade,
  image_path text not null,
  caption text,
  sort_order integer not null default 0,
  created_at timestamptz not null default now()
);

create table if not exists public.services (
  id uuid primary key default gen_random_uuid(),
  master_id uuid not null references public.masters(id) on delete cascade,
  title text not null,
  description text,
  price_from integer not null default 0 check (price_from >= 0),
  duration_minutes integer not null default 60 check (duration_minutes between 15 and 1440),
  is_active boolean not null default true,
  created_at timestamptz not null default now()
);

create table if not exists public.availability_rules (
  id uuid primary key default gen_random_uuid(),
  master_id uuid not null references public.masters(id) on delete cascade,
  weekday smallint not null check (weekday between 0 and 6),
  start_time time not null,
  end_time time not null,
  is_active boolean not null default true,
  check (end_time > start_time),
  unique(master_id, weekday, start_time, end_time)
);

create table if not exists public.blocked_dates (
  id uuid primary key default gen_random_uuid(),
  master_id uuid not null references public.masters(id) on delete cascade,
  starts_at timestamptz not null,
  ends_at timestamptz not null,
  reason text,
  check (ends_at > starts_at)
);

create table if not exists public.bookings (
  id uuid primary key default gen_random_uuid(),
  client_id uuid not null references public.profiles(id) on delete restrict,
  master_id uuid not null references public.masters(id) on delete restrict,
  service_id uuid references public.services(id) on delete set null,
  starts_at timestamptz not null,
  ends_at timestamptz not null,
  status public.booking_status not null default 'pending',
  client_note text,
  master_note text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check (ends_at > starts_at)
);

-- Pending and confirmed bookings reserve the interval. The database, not the UI,
-- is the final guard against two clients taking overlapping time slots.
do $$ begin
  alter table public.bookings
    add constraint bookings_no_overlap
    exclude using gist (
      master_id with =,
      tstzrange(starts_at, ends_at, '[)') with &&
    )
    where (status in ('pending'::public.booking_status, 'confirmed'::public.booking_status));
exception when duplicate_object then null; end $$;

