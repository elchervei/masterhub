-- Public catalog: only approved masters and visible portfolio/services are public.
create policy "profiles are visible to self or approved masters"
on public.profiles for select
using (
  id = auth.uid()
  or exists (select 1 from public.master_profiles mp where mp.id = profiles.id and mp.status = 'approved')
);

create policy "users update own profile"
on public.profiles for update
using (id = auth.uid())
with check (id = auth.uid() and role = (select p.role from public.profiles p where p.id = auth.uid()));

create policy "approved masters are public; owner sees own"
on public.master_profiles for select
using (status = 'approved' or id = auth.uid());

create policy "masters insert own master profile"
on public.master_profiles for insert
with check (id = auth.uid());

create policy "masters update own draft profile"
on public.master_profiles for update
using (id = auth.uid() and status in ('draft', 'rejected'))
with check (id = auth.uid() and status in ('draft', 'pending', 'rejected'));

create policy "styles are public"
on public.master_styles for select using (true);

create policy "style links are public for approved masters or owner"
on public.master_style_links for select
using (
  master_id = auth.uid()
  or exists (select 1 from public.master_profiles mp where mp.id = master_id and mp.status = 'approved')
);

create policy "masters manage own style links"
on public.master_style_links for all
using (master_id = auth.uid())
with check (master_id = auth.uid());

create policy "portfolio public visible or owner"
on public.portfolio_items for select
using (
  (is_visible and exists (select 1 from public.master_profiles mp where mp.id = master_id and mp.status = 'approved'))
  or master_id = auth.uid()
);

create policy "masters manage own portfolio"
on public.portfolio_items for all
using (master_id = auth.uid())
with check (master_id = auth.uid());

create policy "active services public or owner"
on public.services for select
using (
  (is_active and exists (select 1 from public.master_profiles mp where mp.id = master_id and mp.status = 'approved'))
  or master_id = auth.uid()
);

create policy "masters manage own services"
on public.services for all
using (master_id = auth.uid())
with check (master_id = auth.uid());

create policy "availability rules public or owner"
on public.availability_rules for select
using (
  master_id = auth.uid()
  or exists (select 1 from public.master_profiles mp where mp.id = master_id and mp.status = 'approved')
);

create policy "masters manage own availability rules"
on public.availability_rules for all
using (master_id = auth.uid())
with check (master_id = auth.uid());

create policy "availability exceptions public or owner"
on public.availability_exceptions for select
using (
  master_id = auth.uid()
  or exists (select 1 from public.master_profiles mp where mp.id = master_id and mp.status = 'approved')
);

create policy "masters manage own availability exceptions"
on public.availability_exceptions for all
using (master_id = auth.uid())
with check (master_id = auth.uid());

create policy "clients and masters see their bookings"
on public.bookings for select
using (client_id = auth.uid() or master_id = auth.uid());

create policy "clients update own pending bookings to cancel"
on public.bookings for update
using (client_id = auth.uid() and status = 'pending')
with check (client_id = auth.uid() and status = 'cancelled');

create policy "masters update bookings for them"
on public.bookings for update
using (master_id = auth.uid())
with check (master_id = auth.uid());

create policy "users manage own favorites"
on public.favorites for all
using (client_id = auth.uid())
with check (client_id = auth.uid());

create policy "reviews public read"
on public.reviews for select using (true);

create policy "clients create review for completed own booking"
on public.reviews for insert
with check (
  client_id = auth.uid()
  and exists (
    select 1 from public.bookings b
    where b.id = booking_id and b.client_id = auth.uid()
      and b.master_id = master_id and b.status = 'completed'
  )
);

