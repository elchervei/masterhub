create extension if not exists pgcrypto;

do $$ begin
  create type public.user_role as enum ('client', 'master', 'admin');
exception when duplicate_object then null; end $$;

do $$ begin
  create type public.master_status as enum ('draft', 'pending', 'approved', 'rejected', 'blocked');
exception when duplicate_object then null; end $$;

do $$ begin
  create type public.booking_status as enum ('pending', 'confirmed', 'rejected', 'cancelled', 'completed');
exception when duplicate_object then null; end $$;

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  role public.user_role not null default 'client',
  display_name text,
  username text,
  avatar_url text,
  phone text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.master_profiles (
  id uuid primary key references public.profiles(id) on delete cascade,
  slug text unique,
  bio text,
  city text not null default 'Калининград',
  studio_name text,
  address text,
  experience_years integer not null default 0 check (experience_years >= 0),
  status public.master_status not null default 'draft',
  rejection_reason text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.master_styles (
  id bigint generated by default as identity primary key,
  name text not null unique
);

create table if not exists public.master_style_links (
  master_id uuid not null references public.master_profiles(id) on delete cascade,
  style_id bigint not null references public.master_styles(id) on delete cascade,
  primary key (master_id, style_id)
);

create table if not exists public.portfolio_items (
  id uuid primary key default gen_random_uuid(),
  master_id uuid not null references public.master_profiles(id) on delete cascade,
  image_url text not null,
  caption text,
  sort_order integer not null default 0,
  is_visible boolean not null default true,
  created_at timestamptz not null default now()
);

create table if not exists public.services (
  id uuid primary key default gen_random_uuid(),
  master_id uuid not null references public.master_profiles(id) on delete cascade,
  title text not null,
  description text,
  price_from numeric(10,2) check (price_from is null or price_from >= 0),
  duration_minutes integer not null default 60 check (duration_minutes > 0),
  is_active boolean not null default true,
  created_at timestamptz not null default now()
);

create table if not exists public.availability_rules (
  id uuid primary key default gen_random_uuid(),
  master_id uuid not null references public.master_profiles(id) on delete cascade,
  weekday smallint not null check (weekday between 0 and 6),
  start_time time not null,
  end_time time not null,
  is_active boolean not null default true,
  check (end_time > start_time)
);

create table if not exists public.availability_exceptions (
  id uuid primary key default gen_random_uuid(),
  master_id uuid not null references public.master_profiles(id) on delete cascade,
  exception_date date not null,
  is_day_off boolean not null default true,
  start_time time,
  end_time time,
  note text,
  check (
    (is_day_off and start_time is null and end_time is null)
    or
    (not is_day_off and start_time is not null and end_time is not null and end_time > start_time)
  ),
  unique (master_id, exception_date)
);

create table if not exists public.bookings (
  id uuid primary key default gen_random_uuid(),
  client_id uuid not null references public.profiles(id) on delete restrict,
  master_id uuid not null references public.master_profiles(id) on delete restrict,
  service_id uuid references public.services(id) on delete set null,
  starts_at timestamptz not null,
  ends_at timestamptz not null,
  status public.booking_status not null default 'pending',
  client_comment text,
  master_comment text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check (ends_at > starts_at)
);

create index if not exists bookings_master_time_idx on public.bookings(master_id, starts_at, ends_at);
create index if not exists bookings_client_time_idx on public.bookings(client_id, starts_at desc);
create index if not exists portfolio_master_sort_idx on public.portfolio_items(master_id, sort_order);
create index if not exists services_master_active_idx on public.services(master_id, is_active);

create table if not exists public.favorites (
  client_id uuid not null references public.profiles(id) on delete cascade,
  master_id uuid not null references public.master_profiles(id) on delete cascade,
  created_at timestamptz not null default now(),
  primary key (client_id, master_id)
);

create table if not exists public.reviews (
  id uuid primary key default gen_random_uuid(),
  booking_id uuid not null unique references public.bookings(id) on delete cascade,
  client_id uuid not null references public.profiles(id) on delete cascade,
  master_id uuid not null references public.master_profiles(id) on delete cascade,
  rating smallint not null check (rating between 1 and 5),
  text text,
  created_at timestamptz not null default now()
);

-- Automatically create a client profile when a Supabase Auth user appears.
create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  insert into public.profiles (id, display_name, username, avatar_url)
  values (
    new.id,
    coalesce(new.raw_user_meta_data ->> 'full_name', new.raw_user_meta_data ->> 'name'),
    new.raw_user_meta_data ->> 'user_name',
    new.raw_user_meta_data ->> 'avatar_url'
  )
  on conflict (id) do nothing;
  return new;
end;
$$;

drop trigger if exists on_auth_user_created_masterhub on auth.users;
create trigger on_auth_user_created_masterhub
after insert on auth.users
for each row execute procedure public.handle_new_user();

-- A master can request publication; only an admin can approve/block profiles.
create or replace function public.request_master_profile()
returns void
language plpgsql
security invoker
set search_path = ''
as $$
begin
  update public.profiles set role = 'master', updated_at = now()
  where id = auth.uid();

  insert into public.master_profiles (id, status)
  values (auth.uid(), 'pending')
  on conflict (id) do update set status = 'pending', updated_at = now();
end;
$$;

-- Atomic booking creation: serialize requests for one master, then reject overlaps.
create or replace function public.create_booking(
  p_master_id uuid,
  p_service_id uuid,
  p_starts_at timestamptz,
  p_ends_at timestamptz,
  p_client_comment text default null
)
returns uuid
language plpgsql
security invoker
set search_path = ''
as $$
declare
  v_booking_id uuid;
begin
  if auth.uid() is null then
    raise exception 'Authentication required';
  end if;
  if p_ends_at <= p_starts_at then
    raise exception 'Invalid booking duration';
  end if;

  perform 1 from public.master_profiles
  where id = p_master_id and status = 'approved'
  for update;
  if not found then
    raise exception 'Master is unavailable';
  end if;

  if p_service_id is not null and not exists (
    select 1 from public.services
    where id = p_service_id and master_id = p_master_id and is_active = true
  ) then
    raise exception 'Service is unavailable';
  end if;

  if exists (
    select 1 from public.bookings
    where master_id = p_master_id
      and status in ('pending', 'confirmed')
      and starts_at < p_ends_at
      and ends_at > p_starts_at
  ) then
    raise exception 'This time slot is already booked';
  end if;

  insert into public.bookings (client_id, master_id, service_id, starts_at, ends_at, client_comment)
  values (auth.uid(), p_master_id, p_service_id, p_starts_at, p_ends_at, p_client_comment)
  returning id into v_booking_id;

  return v_booking_id;
end;
$$;

